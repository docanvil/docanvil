use regex::{Captures, Regex};
use std::collections::{BTreeSet, HashMap, HashSet};
use std::sync::LazyLock;

/// Pre-comrak pass: extract custom heading IDs from `### Heading {#custom-id}`
/// syntax and move them to a separate line so the attributes pipeline can
/// process them after comrak renders the heading.
///
/// Converts:
///   `### My Great Heading {#custom-id}`
/// Into:
///   `### My Great Heading\n\n{#custom-id}`
pub fn extract_custom_heading_ids(source: &str) -> String {
    // The trailing whitespace is deliberately `[ \t]*`, not `\s*`: `\s` matches
    // `\n` too, so a greedy `\s*$` would eat into the blank line that follows
    // (`{#id}\n\n` has two newlines; `\s*` would swallow one), leaving the next
    // paragraph as a lazy continuation of the `{#id}` line instead of its own block.
    static HEADING_ID_RE: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"(?m)^(#{1,6}\s+.*?)\s+\{#([\w-]+)\}[ \t]*$").unwrap());

    HEADING_ID_RE
        .replace_all(source, "$1\n\n{#$2}")
        .into_owned()
}

/// Decode character references once, after stripping actual markup. Decoding
/// first would mistake escaped literal tags for markup and discard their text.
pub(crate) fn decode_entities(text: &str) -> String {
    static ENTITY_RE: LazyLock<Regex> = LazyLock::new(|| {
        Regex::new(r"&(?:#[xX][0-9a-fA-F]+|#[0-9]+|[A-Za-z][A-Za-z0-9]+);").unwrap()
    });
    static NAMED: LazyLock<HashMap<&'static str, &'static str>> = LazyLock::new(|| {
        entities::ENTITIES
            .iter()
            .map(|e| (e.entity, e.characters))
            .collect()
    });
    ENTITY_RE
        .replace_all(text, |caps: &Captures| {
            let entity = &caps[0];
            if let Some(number) = entity.strip_prefix("&#") {
                let number = number.trim_end_matches(';');
                let value = if let Some(hex) = number.strip_prefix(['x', 'X']) {
                    u32::from_str_radix(hex, 16)
                } else {
                    number.parse::<u32>()
                };
                return value
                    .ok()
                    .and_then(char::from_u32)
                    .filter(|c| *c != '\0')
                    .unwrap_or('\u{FFFD}')
                    .to_string();
            }
            NAMED.get(entity).copied().unwrap_or(entity).to_string()
        })
        .into_owned()
}

/// Post-comrak pass: inject `id` attributes into `<h1>`–`<h6>` tags that
/// don't already have one. IDs are generated by slugifying the text content.
/// Duplicate slugs get `-1`, `-2`, etc. appended.
pub fn inject_heading_ids(html: &str) -> String {
    static HEADING_RE: LazyLock<Regex> =
        LazyLock::new(|| Regex::new(r"<(h[1-6])([^>]*)>(.*?)</h[1-6]>").unwrap());
    static TAG_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"<[^>]+>").unwrap());
    static ID_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r#"\bid\s*=\s*""#).unwrap());

    let mut used: HashSet<_> = anchor_ids(html).into_iter().collect();
    let mut seen: HashMap<String, usize> = HashMap::new();

    HEADING_RE
        .replace_all(html, |caps: &Captures| {
            let tag = &caps[1];
            let attrs = &caps[2];
            let inner = &caps[3];

            // Skip if there's already an id attribute
            if ID_RE.is_match(attrs) {
                return caps[0].to_string();
            }

            // Strip HTML tags from inner content to get plain text
            let text = TAG_RE.replace_all(inner, "");
            let text = decode_entities(&text);
            let base_slug = slug::slugify(text.trim());

            let id = if base_slug.is_empty() {
                "heading".to_string()
            } else {
                base_slug
            };

            // Handle duplicates
            let count = seen.entry(id.clone()).or_insert(0);
            let final_id = loop {
                let candidate = if *count == 0 {
                    id.clone()
                } else {
                    format!("{id}-{count}")
                };
                *count += 1;
                if used.insert(candidate.clone()) {
                    break candidate;
                }
            };

            format!("<{} id=\"{}\"{}>{}</{}>", tag, final_id, attrs, inner, tag)
        })
        .into_owned()
}

/// IDs actually present in rendered HTML, including native media controls.
pub(crate) fn anchor_ids(html: &str) -> BTreeSet<String> {
    static IDS: LazyLock<Regex> = LazyLock::new(|| Regex::new(r#"<[^>]+\s+id="([^"]*)""#).unwrap());
    IDS.captures_iter(html)
        .map(|capture| decode_entities(&capture[1]))
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::pipeline::markdown;

    #[test]
    fn generated_ids_avoid_explicit_ids_and_naturally_suffixed_headings() {
        let html = "<h2>Foo</h2><h2 id=\"foo\">Explicit</h2><h2>Foo</h2><h2>Foo 1</h2><section id=\"heading\"></section><h2>!!!</h2>";
        let rendered = inject_heading_ids(html);
        let ids = anchor_ids(&rendered);
        assert_eq!(ids.len(), 6, "{rendered}");
        assert!(ids.contains("foo-1-1"));
        assert!(ids.contains("heading-1"));
        assert_eq!(inject_heading_ids(&rendered), rendered);
    }

    #[test]
    fn basic_heading_gets_id() {
        let html = "<h2>Installation Guide</h2>";
        let result = inject_heading_ids(html);
        assert_eq!(
            result,
            r#"<h2 id="installation-guide">Installation Guide</h2>"#
        );
    }

    #[test]
    fn heading_with_existing_id_not_modified() {
        let html = r#"<h2 id="custom-id">Title</h2>"#;
        let result = inject_heading_ids(html);
        assert_eq!(result, html);
    }

    #[test]
    fn duplicate_headings_get_suffixed_ids() {
        let html = "<h2>Foo</h2>\n<h2>Foo</h2>\n<h2>Foo</h2>";
        let result = inject_heading_ids(html);
        assert!(result.contains(r#"id="foo""#));
        assert!(result.contains(r#"id="foo-1""#));
        assert!(result.contains(r#"id="foo-2""#));
    }

    #[test]
    fn tags_inside_headings_stripped_for_slug() {
        let html = "<h2>Hello <code>world</code></h2>";
        let result = inject_heading_ids(html);
        assert!(result.contains(r#"id="hello-world""#));
        // Inner HTML preserved
        assert!(result.contains("<code>world</code>"));
    }

    #[test]
    fn h1_through_h6_all_handled() {
        let html = "<h1>A</h1><h3>B</h3><h6>C</h6>";
        let result = inject_heading_ids(html);
        assert!(result.contains(r#"<h1 id="a">"#));
        assert!(result.contains(r#"<h3 id="b">"#));
        assert!(result.contains(r#"<h6 id="c">"#));
    }

    #[test]
    fn heading_with_em_tag() {
        let html = "<h2>Getting <em>Started</em></h2>";
        let result = inject_heading_ids(html);
        assert!(result.contains(r#"id="getting-started""#));
    }

    #[test]
    fn preserves_existing_classes() {
        let html = r#"<h2 class="special">Title</h2>"#;
        let result = inject_heading_ids(html);
        assert!(result.contains(r#"id="title""#));
        assert!(result.contains(r#"class="special""#));
    }

    #[test]
    fn heading_entities_are_decoded_once_after_stripping_tags() {
        for (inner, expected) in [
            ("Fish &amp; Chips", "fish-chips"),
            ("Don&#39;t panic", "don-t-panic"),
            ("Don&#x27;t panic", "don-t-panic"),
            ("Don&#X27;t panic", "don-t-panic"),
            (
                "&quot;Hello&quot; &lt;em&gt;world&lt;/em&gt;",
                "hello-em-world-em",
            ),
            ("caf&eacute;&nbsp;menu", "cafe-menu"),
            ("<em>Fish</em> &amp; Chips", "fish-chips"),
            ("Literal &amp;lt;tag&amp;gt;", "literal-lt-tag-gt"),
        ] {
            let html = format!("<h2>{inner}</h2>");
            assert_eq!(
                inject_heading_ids(&html),
                format!("<h2 id=\"{expected}\">{inner}</h2>")
            );
        }
    }

    #[test]
    fn decoded_heading_duplicates_and_explicit_ids() {
        let html = "<h2>Fish &amp; Chips</h2><h2>Fish &#38; Chips</h2><h2 id=\"fish-amp-chips\">Fish &amp; Chips</h2>";
        assert_eq!(
            inject_heading_ids(html),
            "<h2 id=\"fish-chips\">Fish &amp; Chips</h2><h2 id=\"fish-chips-1\">Fish &#38; Chips</h2><h2 id=\"fish-amp-chips\">Fish &amp; Chips</h2>"
        );
    }

    #[test]
    fn malformed_entities_remain_literal_and_invalid_codepoints_do_not_panic() {
        assert_eq!(
            decode_entities("&unknown; &#no; &amp &#xZZ;"),
            "&unknown; &#no; &amp &#xZZ;"
        );
        assert_eq!(
            decode_entities("&#0; &#xD800; &#99999999999999999999;"),
            "� � �"
        );
    }

    // --- extract_custom_heading_ids tests ---

    #[test]
    fn custom_heading_id_extracted() {
        let source = "### My Great Heading {#custom-id}";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "### My Great Heading\n\n{#custom-id}");
    }

    #[test]
    fn custom_heading_id_h1() {
        let source = "# Top Level {#top}";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "# Top Level\n\n{#top}");
    }

    #[test]
    fn custom_heading_id_h6() {
        let source = "###### Deep Heading {#deep}";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "###### Deep Heading\n\n{#deep}");
    }

    #[test]
    fn heading_without_custom_id_unchanged() {
        let source = "## Normal Heading";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "## Normal Heading");
    }

    #[test]
    fn multiple_headings_with_custom_ids() {
        let source = "## First {#one}\n\nSome text\n\n### Second {#two}";
        let result = extract_custom_heading_ids(source);
        assert_eq!(
            result,
            "## First\n\n{#one}\n\nSome text\n\n### Second\n\n{#two}"
        );
    }

    /// Regression test: the blank line after `{#id}` must survive, or the
    /// following paragraph becomes a lazy continuation of the `{#id}` line
    /// and comrak renders them as one `<p>`, leaking `{#id}` into the page.
    #[test]
    fn blank_line_after_custom_id_is_preserved() {
        let source = "## Heading {#my-id}\n\nFollowing paragraph.";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "## Heading\n\n{#my-id}\n\nFollowing paragraph.");

        let html = markdown::render(&result);
        assert_eq!(
            html,
            "<h2>Heading</h2>\n<p>{#my-id}</p>\n<p>Following paragraph.</p>\n"
        );
    }

    #[test]
    fn custom_id_with_hyphens() {
        let source = "## API Reference {#api-v2-reference}";
        let result = extract_custom_heading_ids(source);
        assert_eq!(result, "## API Reference\n\n{#api-v2-reference}");
    }
}
